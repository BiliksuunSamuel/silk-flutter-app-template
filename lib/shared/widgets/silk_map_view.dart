/// An interactive map (flutter_map + OpenStreetMap — no API key needed).
/// Shows the full world by default, or zooms in to fill the viewport with a
/// specific country when [countryCode] (ISO 3166-1 alpha-2) is supplied.
///
/// Pass [height] for inline use. Omit it inside a parent that already
/// provides a bounded height (Expanded / full-screen Scaffold body).
class SilkMapView extends StatefulWidget {
  const SilkMapView({
    this.countryCode,
    this.height = 300,
    this.borderRadius,
    super.key,
  });

  /// ISO 3166-1 alpha-2 code (e.g. 'GH', 'US'). Null shows the world view.
  final String? countryCode;

  /// Fixed height. Set to null when the parent constrains the height.
  final double? height;

  /// Corner radius. Defaults to the theme's large radius token.
  final double? borderRadius;

  @override
  State<SilkMapView> createState() => _SilkMapViewState();
}

class _SilkMapViewState extends State<SilkMapView> {
  final _controller = MapController();

  @override
  void didUpdateWidget(SilkMapView old) {
    super.didUpdateWidget(old);
    if (old.countryCode != widget.countryCode) {
      WidgetsBinding.instance.addPostFrameCallback((_) => _fitCamera());
    }
  }

  void _fitCamera() {
    final code = widget.countryCode?.toUpperCase();
    if (code == null || !_kBounds.containsKey(code)) {
      _controller.fitCamera(
        const CameraFit.coordinates(
          coordinates: [LatLng(-60, -160), LatLng(75, 160)],
          padding: EdgeInsets.zero,
        ),
      );
      return;
    }
    final b = _kBounds[code]!;
    _controller.fitCamera(
      CameraFit.bounds(
        bounds: LatLngBounds(LatLng(b[0], b[1]), LatLng(b[2], b[3])),
        padding: const EdgeInsets.all(12),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final tokens = context.tokens;
    final radius = widget.borderRadius ?? tokens.radiusLg;

    final map = ClipRRect(
      borderRadius: BorderRadius.circular(radius),
      child: FlutterMap(
        mapController: _controller,
        options: MapOptions(
          initialCenter: const LatLng(20, 0),
          initialZoom: 2,
          onMapReady: _fitCamera,
        ),
        children: [
          TileLayer(
            // CartoDB Voyager — free, no API key, full road/POI detail,
            // Google Maps-like navigation style.
            urlTemplate:
                'https://{s}.basemaps.cartocdn.com/rastertiles/voyager/{z}/{x}/{y}{r}.png',
            subdomains: const ['a', 'b', 'c', 'd'],
            userAgentPackageName: 'com.silk.app',
            maxZoom: 19,
          ),
        ],
      ),
    );

    final h = widget.height;
    return h != null ? SizedBox(height: h, child: map) : map;
  }
}
